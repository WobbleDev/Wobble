// Build the versioned Short form snapshot from filtered source inputs (ADR 0046, ticket 05).
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { applyGates, keyOf, normalizePhrase } from './gates.mjs';
import { sha256Hex } from './fetch.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '../..');

const LANGUAGE_OF = { en: 'en', es: 'es' };
const ALIAS_SHAPE = /^[A-Za-z][A-Za-z0-9&.-]{1,5}$/;

export function extractOnetPairs(row) {
	const title = typeof row.job_title === 'string' ? row.job_title : '';
	const match = title.match(/^(.*?)\s*\(\s*([^()]{1,8})\s*\)\s*(.*?)$/);
	if (match === null) return [];
	const left = match[1].trim();
	const inside = match[2].trim();
	const right = match[3].trim();
	if (!ALIAS_SHAPE.test(inside)) return [];
	const out = [];
	if (left !== '' && [...left].length > [...inside].length)
		out.push({ expansion: left, short: inside });
	if (right !== '' && [...right].length > [...inside].length)
		out.push({ expansion: right, short: inside });
	return out.map((pair) => ({ ...pair, list: 'acronyms', language: 'en', source: 'onet' }));
}

export function extractKaikkiPairs(record) {
	const language = LANGUAGE_OF[record.lang_code];
	if (language === undefined || !Array.isArray(record.senses)) return [];
	const pairs = [];
	for (const sense of record.senses) {
		if (!Array.isArray(sense.tags) || !Array.isArray(sense.alt_of) || sense.alt_of.length !== 1)
			continue;
		const tags = sense.tags.map((tag) => String(tag).toLowerCase());
		const acronym = tags.indexOf('acronym') !== -1 || tags.indexOf('initialism') !== -1;
		const word = tags.indexOf('abbreviation') !== -1;
		if ((!acronym && !word) || typeof sense.alt_of[0].word !== 'string') continue;
		pairs.push({
			expansion: sense.alt_of[0].word,
			short: record.word,
			list: acronym ? 'acronyms' : 'words',
			language,
			source: 'kaikki'
		});
	}
	return pairs;
}

export function extractWikidataPairs(item) {
	const pairs = [];
	for (const language of ['en', 'es']) {
		const labels = item.label !== undefined && typeof item.label === 'object' ? item.label : {};
		const expansion = labels[language];
		if (typeof expansion !== 'string' || expansion === '') continue;
		const p1813 = item.p1813 !== undefined ? item.p1813[language] || [] : [];
		const aliases = item.aliases !== undefined ? item.aliases[language] || [] : [];
		for (const short of [...p1813, ...aliases]) {
			if (typeof short !== 'string' || !ALIAS_SHAPE.test(short)) continue;
			if (keyOf(short) === keyOf(expansion)) continue;
			pairs.push({ expansion, short, list: 'acronyms', language, source: 'wikidata' });
		}
	}
	return pairs;
}

export function splitDuplicates(kept) {
	const seen = new Set();
	const unique = [];
	let duplicates = 0;
	for (const pair of kept) {
		const key = [pair.language, pair.list, pair.expansion, pair.short].join('\u0000');
		if (seen.has(key)) {
			duplicates += 1;
			continue;
		}
		seen.add(key);
		unique.push(pair);
	}
	return { unique, duplicates };
}

export function splitGroups(kept) {
	const groups = { en: { words: [], acronyms: [] }, es: { words: [], acronyms: [] } };
	for (const pair of kept) {
		const bucket =
			groups[pair.language] === undefined ? undefined : groups[pair.language][pair.list];
		if (bucket === undefined) continue;
		bucket.push([pair.expansion, pair.short]);
	}
	const byKey = (left, right) =>
		keyOf(left[0]).localeCompare(keyOf(right[0])) || keyOf(left[1]).localeCompare(keyOf(right[1]));
	for (const language of Object.values(groups))
		for (const bucket of Object.values(language)) bucket.sort(byKey);
	return groups;
}

function rustQuote(text) {
	return text.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

export function renderSnapshot(revision, groups, note) {
	const lines = [];
	lines.push('//! Generated by "node scripts/short-form-lists/build.mjs" (ticket 05, ADR 0046).');
	lines.push('//! Do not hand-edit: rerun the build from the filtered inputs; it rewrites this');
	lines.push('//! file, the build report and NOTICE together. Pairs failing a gate in gates.mjs');
	lines.push('//! are dropped and counted in the report, never written here. An ambiguous short');
	lines.push('//! form keeps every expansion that passed, for the worksite conflict check.');
	lines.push('//!');
	lines.push(`//! ${note}`);
	lines.push('');
	lines.push('/// The revision of the filtered inputs and gate results below.');
	lines.push(`pub const REVISION: &str = "${rustQuote(revision)}";`);
	const table = (name, doc, pairs) => {
		lines.push('');
		lines.push(doc);
		lines.push(`pub static ${name}: &[(&str, &str)] = &[`);
		for (const [expansion, short] of pairs)
			lines.push(`    ("${rustQuote(expansion)}", "${rustQuote(short)}"),`);
		lines.push('];');
	};
	table('ENGLISH_WORDS', '/// English whole word -> its shortening.', groups.en.words);
	table(
		'ENGLISH_ACRONYMS',
		'/// English whole-word phrase -> the sourced acronym; ambiguous acronyms keep every expansion.',
		groups.en.acronyms
	);
	table('SPANISH_WORDS', '/// Spanish whole word -> its shortening.', groups.es.words);
	table(
		'SPANISH_ACRONYMS',
		'/// Spanish whole-word phrase -> the sourced acronym.',
		groups.es.acronyms
	);
	return lines.join('\n') + '\n';
}

