export function comparePairs(left, right) {
	return (
		keyOf(left.expansion).localeCompare(keyOf(right.expansion)) ||
		keyOf(left.short).localeCompare(keyOf(right.short))
	);
}

export async function build({ inputDir, snapshotPath, reportPath, noticePath }) {
	const manifest = JSON.parse(await readFile(join(inputDir, 'manifest.json'), 'utf8'));
	const texts = new Map();
	for (const file of manifest.files) {
		const text = await readFile(join(inputDir, file.path), 'utf8');
		if (sha256Hex(text) !== file.sha256) throw new Error(file.path + ': checksum mismatch');
		texts.set(file.path, text);
	}
	const candidates = [];
	for (const file of manifest.files) {
		const text = texts.get(file.path);
		if (file.path.indexOf('onet') === 0) {
			for (const row of JSON.parse(text)) candidates.push(...extractOnetPairs(row));
		} else if (file.path.indexOf('kaikki') === 0) {
			for (const line of text.split('\n')) {
				if (line.trim() === '') continue;
				candidates.push(...extractKaikkiPairs(JSON.parse(line)));
			}
		} else if (file.path.indexOf('wikidata') === 0) {
			for (const item of JSON.parse(text).items) candidates.push(...extractWikidataPairs(item));
		} else {
			throw new Error(file.path + ': no extractor (name it onet-*, kaikki-* or wikidata-*)');
		}
	}
	const gated = applyGates(candidates);
	const stored = gated.kept.map((pair) => ({
		...pair,
		expansion: keyOf(pair.expansion),
		short: pair.list === 'words' ? keyOf(pair.short) : normalizePhrase(pair.short)
	}));
	const deduped = splitDuplicates(stored);
	const groups = splitGroups(deduped.unique);
	const note =
		typeof manifest.note === 'string' ? manifest.note : 'Built from the committed filtered inputs.';
	await mkdir(dirname(snapshotPath), { recursive: true });
	await writeFile(snapshotPath, renderSnapshot(manifest.revision, groups, note));
	const report = {
		revision: manifest.revision,
		generatedBy: 'scripts/short-form-lists/build.mjs',
		inputs: manifest.files,
		kept: {
			en: { words: groups.en.words.length, acronyms: groups.en.acronyms.length },
			es: { words: groups.es.words.length, acronyms: groups.es.acronyms.length }
		},
		droppedTotal: gated.dropped.length,
		duplicatePairs: deduped.duplicates,
		dropped: gated.dropped
			.map((pair) => ({
				short: pair.short,
				expansion: pair.expansion,
				reason: pair.reason,
				source: pair.source,
				language: pair.language
			}))
			.sort(comparePairs)
	};
	await mkdir(dirname(reportPath), { recursive: true });
	await writeFile(reportPath, JSON.stringify(report, null, '\t') + '\n');
	await mkdir(dirname(noticePath), { recursive: true });
	await writeFile(
		noticePath,
		renderNotice(manifest.revision, gated.kept.length, gated.dropped.length)
	);
	return { kept: gated.kept.length, dropped: gated.dropped.length };
}

async function main() {
	const args = process.argv.slice(2);
	const inFlag = args.indexOf('--in');
	const inputDir = inFlag === -1 ? join(here, 'filtered-input') : args[inFlag + 1];
	if (inputDir === undefined) throw new Error('--in needs a directory');
	const summary = await build({
		inputDir,
		snapshotPath: join(repoRoot, 'crates/wobble-core/src/short_form_lists_generated.rs'),
		reportPath: join(here, 'build-report.json'),
		noticePath: join(repoRoot, 'NOTICE')
	});
	console.log(
		'snapshot, build-report.json and NOTICE written: ' +
			summary.kept +
			' kept, ' +
			summary.dropped +
			' dropped'
	);
}

const invokedAsScript = process.argv[1] !== undefined && process.argv[1].endsWith('build.mjs');
if (invokedAsScript) {
	main().catch((error) => {
		console.error(error.message);
		process.exitCode = 1;
	});
}
